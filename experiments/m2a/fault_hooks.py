"""Deterministic harness-owned M2a fault injection hooks.

The pipeline runner receives ``PipelineInputs`` and the evaluator separately
receives ``EvaluatorRecord``. Detector code must receive neither object. It
must receive only ordinary pipeline observations after execution. These hooks
are development-only until the protocol freeze.
"""

from __future__ import annotations

import hashlib
import json
import math
from dataclasses import dataclass
from decimal import Decimal
from pathlib import Path
from typing import Callable

import polars as pl

ROOT = Path(__file__).resolve().parents[2]
CATALOG_PATH = ROOT / "experiments/m2a/catalog/fault_catalog_v2.json"
SUPPORTED_SEVERITIES = {"low", "medium", "high"}
SUPPORTED_SEEDS = {11, 29, 47}
ORDINAL = "__dic_source_row_ordinal"


@dataclass(frozen=True)
class PipelineInputs:
    """Inputs and stage hooks for the pipeline runner, not for detectors."""

    source: pl.DataFrame
    lookup: pl.DataFrame | None
    stage_hooks: dict[str, Callable[..., pl.DataFrame]]


@dataclass(frozen=True)
class EvaluatorRecord:
    """Private injection facts. Never serialize this beside detector inputs."""

    fault_id: str
    stage: str
    locus: str
    severity: str
    seed: int
    parameters: dict[str, object]
    selected_ordinals: list[int] | tuple[int, ...] = ()
    selected_keys: list[object] | tuple[object, ...] = ()


def _catalog() -> dict:
    return json.loads(CATALOG_PATH.read_text(encoding="utf-8"))


def _case(fault_id: str, severity: str, seed: int) -> tuple[dict, dict]:
    if severity not in SUPPORTED_SEVERITIES:
        raise ValueError(f"Unsupported severity: {severity}")
    if seed not in SUPPORTED_SEEDS:
        raise ValueError(f"Unsupported seed: {seed}")
    matches = [m for m in _catalog()["mechanisms"] if m["fault_id"] == fault_id]
    if len(matches) != 1:
        raise ValueError(f"Unknown fault mechanism: {fault_id}")
    mechanism = matches[0]
    if mechanism["split"] != "development":
        raise ValueError("Held-out mechanisms cannot be generated by the development injector")
    if seed not in mechanism["seeds"]:
        raise ValueError(f"Seed {seed} is not registered for {fault_id}")
    return mechanism, dict(mechanism["severity_parameters"][severity])


def _stable_key(fault_id: str, seed: int, ordinal: int) -> bytes:
    material = f"{fault_id}|{seed}|{ordinal}".encode("utf-8")
    return hashlib.sha256(material).digest()


def _ordinals(frame: pl.DataFrame) -> list[int]:
    if "source_row_ordinal" in frame.columns:
        values = frame.get_column("source_row_ordinal").to_list()
        if any(value is None for value in values) or len(set(values)) != len(values):
            raise ValueError("source_row_ordinal must be non-null and unique")
        return [int(value) for value in values]
    return list(range(frame.height))


def _select(fault_id: str, seed: int, ordinals: list[int], count: int) -> list[int]:
    if count < 1 or count > len(ordinals):
        raise ValueError(f"Selection count {count} is invalid for {len(ordinals)} candidates")
    return sorted(ordinals, key=lambda ordinal: (_stable_key(fault_id, seed, ordinal), ordinal))[:count]


def _fraction_count(fraction: float, candidates: int) -> int:
    if not 0 < fraction <= 1:
        raise ValueError("selected_fraction must be in (0, 1]")
    if candidates <= 0:
        raise ValueError("No eligible rows or groups for deterministic injection")
    return min(candidates, max(1, math.ceil(fraction * candidates)))


def _selection_column(frame: pl.DataFrame) -> str:
    return "source_row_ordinal" if "source_row_ordinal" in frame.columns else ORDINAL


def _select_frame(frame: pl.DataFrame, fault_id: str, seed: int,
                  eligible: pl.Expr | None, fraction: float) -> tuple[list[int], str]:
    indexed = frame.with_row_index(ORDINAL)
    if eligible is not None:
        indexed = indexed.filter(eligible.fill_null(False))
    selection_column = _selection_column(frame)
    candidates = indexed.select(selection_column).to_series().to_list()
    chosen = _select(fault_id, seed, candidates, _fraction_count(fraction, len(candidates)))
    return chosen, selection_column


def _split_selected(frame: pl.DataFrame, values: list[int]) -> tuple[pl.DataFrame, pl.DataFrame]:
    indexed = frame if ORDINAL in frame.columns else frame.with_row_index(ORDINAL)
    condition = pl.col(_selection_column(frame)).is_in(values)
    selected = indexed.filter(condition)
    other = indexed.filter(~condition)
    return selected, other


def _with_ordinal(frame: pl.DataFrame) -> tuple[pl.DataFrame, bool]:
    if "source_row_ordinal" in frame.columns:
        _ordinals(frame)
        return frame, False
    return frame.with_row_index("source_row_ordinal"), True


def _add_hook_ordinal(frame: pl.DataFrame) -> tuple[pl.DataFrame, bool, str]:
    if "source_row_ordinal" in frame.columns:
        _ordinals(frame)
        return frame, False, "source_row_ordinal"
    if ORDINAL in frame.columns:
        raise ValueError(f"Input uses reserved internal column {ORDINAL}")
    return frame.with_row_index(ORDINAL), True, ORDINAL


def prepare_case(fault_id: str, severity: str, seed: int,
                 source: pl.DataFrame, lookup: pl.DataFrame | None = None
                 ) -> tuple[PipelineInputs, EvaluatorRecord]:
    """Prepare a development case and keep evaluator facts in a separate return value.

    The harness provides the first tuple element to the pipeline runner only.
    It must not expose stage hooks or evaluator facts to detector code.
    Code-fault hooks use the same function signature as their named pipeline stage.
    """
    mechanism, parameters = _case(fault_id, severity, seed)
    stage = mechanism["stage"]
    locus = mechanism["locus"]
    hooks: dict[str, Callable[..., pl.DataFrame]] = {}
    selected_ordinals: list[int] = []
    selected_keys: list[object] = []
    detector_source = source.clone()
    detector_lookup = lookup.clone() if lookup is not None else None

    if fault_id in {"ingestion_duplicate_records", "ingestion_missing_records"}:
        indexed, added = _with_ordinal(detector_source)
        candidates = indexed.get_column("source_row_ordinal").to_list()
        if fault_id == "ingestion_duplicate_records":
            count = int(parameters["duplicate_rows"])
            selected_ordinals = _select(fault_id, seed, candidates, count)
            copies = indexed.filter(pl.col("source_row_ordinal").is_in(selected_ordinals))
            detector_source = pl.concat([indexed, copies], how="vertical")
        else:
            count = _fraction_count(float(parameters["removed_fraction"]), len(candidates))
            selected_ordinals = _select(fault_id, seed, candidates, count)
            detector_source = indexed.filter(~pl.col("source_row_ordinal").is_in(selected_ordinals))
        if added:
            detector_source = detector_source.drop("source_row_ordinal")

    elif fault_id == "join_duplicate_lookup_key":
        if detector_lookup is None or "LocationID" not in detector_lookup.columns:
            raise ValueError("join_duplicate_lookup_key requires lookup.LocationID")
        if "PULocationID" not in detector_source.columns:
            raise ValueError("join_duplicate_lookup_key requires source.PULocationID")
        matched = set(detector_source.get_column("PULocationID").drop_nulls().to_list())
        keys = [key for key in detector_lookup.get_column("LocationID").drop_nulls().unique().to_list()
                if key in matched]
        keys = sorted(keys)
        selected_keys = _select(fault_id, seed, list(range(len(keys))), 1)
        key = keys[selected_keys[0]]
        row = detector_lookup.filter(pl.col("LocationID") == key).head(1)
        copies = pl.concat([row] * int(parameters["duplicate_copies"]), how="vertical")
        detector_lookup = pl.concat([detector_lookup, copies], how="vertical")
        selected_keys = [key]

    elif fault_id == "cleaning_fare_threshold":
        if "fare_amount" not in detector_source.columns:
            raise ValueError("cleaning_fare_threshold requires source.fare_amount")
        threshold = float(parameters["threshold"])
        eligible = pl.col("fare_amount").cast(pl.Float64, strict=False).is_between(0, threshold, closed="left")
        selected_ordinals, _ = _select_frame(
            detector_source, fault_id, seed, eligible, float(parameters["selected_fraction"])
        )

        def hook(frame: pl.DataFrame, baseline_stage: Callable[[pl.DataFrame], pl.DataFrame] | None = None,
                 *_: object, **__: object) -> pl.DataFrame:
            if baseline_stage is None:
                raise ValueError("cleaning hook requires the baseline cleaning stage")
            tagged, added, id_column = _add_hook_ordinal(frame)
            baseline = baseline_stage(tagged)
            if id_column not in baseline.columns:
                raise ValueError("baseline cleaning stage discarded the harness row ordinal")
            result = baseline.filter(~pl.col(id_column).is_in(selected_ordinals))
            return result.drop(id_column) if added else result

        hooks["cleaning"] = hook

    elif fault_id == "cleaning_timestamp_offset":
        minutes = int(parameters["shift_minutes"])
        fraction = float(parameters["selected_fraction"])
        selected_ordinals, _ = _select_frame(detector_source, fault_id, seed, None, fraction)

        def hook(frame: pl.DataFrame, baseline_stage: Callable[[pl.DataFrame], pl.DataFrame] | None = None,
                 *_: object, **__: object) -> pl.DataFrame:
            if baseline_stage is None:
                raise ValueError("cleaning hook requires the baseline cleaning stage")
            tagged, added, id_column = _add_hook_ordinal(frame)
            selected, other = _split_selected(tagged, selected_ordinals)
            timestamp = "tpep_pickup_datetime"
            shifted = selected.with_columns(
                (pl.col(timestamp).cast(pl.Datetime, strict=False) + pl.duration(minutes=minutes)).alias(timestamp)
            )
            combined = pl.concat([shifted, other], how="vertical").sort(id_column)
            cleaned = baseline_stage(combined)
            if id_column not in cleaned.columns:
                raise ValueError("baseline cleaning stage discarded the harness row ordinal")
            return cleaned.drop(id_column) if added else cleaned

        hooks["cleaning"] = hook

    elif fault_id == "join_wrong_key":
        if detector_lookup is None:
            raise ValueError("join_wrong_key requires a lookup frame")
        if not {"PULocationID", "DOLocationID"}.issubset(detector_source.columns):
            raise ValueError("join_wrong_key requires PULocationID and DOLocationID")
        fraction = float(parameters["selected_fraction"])
        eligible = pl.col("PULocationID") != pl.col("DOLocationID")
        selected_ordinals, _ = _select_frame(detector_source, fault_id, seed, eligible, fraction)

        def hook(trips: pl.DataFrame, lookup_frame: pl.DataFrame | None = None,
                 *_: object, **__: object) -> pl.DataFrame:
            lookup_frame = lookup_frame if lookup_frame is not None else detector_lookup
            selected, other = _split_selected(trips, selected_ordinals)
            selected = selected.drop(ORDINAL)
            other = other.drop(ORDINAL)
            right_key = "LocationID"
            good = other.join(lookup_frame, left_on="PULocationID", right_on=right_key, how="left")
            bad = selected.join(lookup_frame, left_on="DOLocationID", right_on=right_key, how="left")
            combined = pl.concat([good, bad], how="diagonal_relaxed")
            return combined.sort("source_row_ordinal") if "source_row_ordinal" in trips.columns else combined

        hooks["join"] = hook

    elif fault_id in {"aggregation_sum_to_mean", "aggregation_wrong_grouping_key"}:
        fraction_name = "affected_group_fraction" if fault_id == "aggregation_sum_to_mean" else "selected_row_fraction"
        fraction = float(parameters[fraction_name])

        def hook(frame: pl.DataFrame, group_columns: list[str] | None = None,
                 *_: object, **__: object) -> pl.DataFrame:
            if fault_id == "aggregation_wrong_grouping_key":
                if "dropoff_date" not in frame.columns:
                    raise ValueError("aggregation_wrong_grouping_key requires dropoff_date")
                if "pickup_date" not in frame.columns:
                    raise ValueError("aggregation_wrong_grouping_key requires pickup_date")
                eligible_rows = pl.col("pickup_date") != pl.col("dropoff_date")
                row_ids, _ = _select_frame(frame, fault_id, seed, eligible_rows, fraction)
                selected_ordinals.extend(row_ids)
                indexed = frame.with_row_index(ORDINAL)
                selected = pl.col(_selection_column(frame)).is_in(row_ids)
                corrupted = indexed.with_columns(
                    pl.when(selected).then(pl.col("dropoff_date")).otherwise(pl.col("pickup_date")).alias("pickup_date")
                ).drop(ORDINAL)
                columns = list(group_columns or ["pickup_date", "pickup_zone"])
                return corrupted.group_by(columns).agg(
                    pl.col("fare_amount").cast(pl.Decimal(precision=18, scale=2), strict=False)
                    .sum().alias("fare_amount")
                ).sort(columns)
            columns = list(group_columns or ["pickup_date", "pickup_zone"])
            fare = pl.col("fare_amount").cast(pl.Decimal(precision=18, scale=2), strict=False)
            joined = frame.group_by(columns).agg(
                fare.sum().alias("__fault_sum"),
                fare.count().alias("__fault_count"),
            ).sort(columns)
            means = [
                float(total / Decimal(count)) if total is not None and count else None
                for total, count in joined.select("__fault_sum", "__fault_count").iter_rows()
            ]
            joined = joined.with_columns(pl.Series("__fault_mean", means, dtype=pl.Float64))
            keys = joined.select(columns).rows()
            ranks = sorted(range(len(keys)), key=lambda i: (
                hashlib.sha256((f"{fault_id}|{seed}|" + json.dumps(keys[i], default=str, separators=(",", ":"))).encode()).digest(),
                json.dumps(keys[i], default=str, separators=(",", ":")),
            ))
            count = _fraction_count(fraction, len(keys))
            chosen = set(ranks[:count])
            selected_keys.extend(keys[index] for index in sorted(chosen))
            selector = pl.Series("__selected_group", [i in chosen for i in range(len(keys))])
            result = joined.with_columns(selector).with_columns(
                pl.when(pl.col("__selected_group")).then(pl.col("__fault_mean")).otherwise(pl.col("__fault_sum").cast(pl.Float64)).alias("fare_amount")
            ).drop(["__selected_group", "__fault_mean", "__fault_sum", "__fault_count"])
            return result.sort(columns)

        hooks["aggregation"] = hook

    else:
        raise ValueError(f"No injector is implemented for {fault_id}")

    truth = EvaluatorRecord(
        fault_id=fault_id,
        stage=stage,
        locus=locus,
        severity=severity,
        seed=seed,
        parameters=parameters,
        selected_ordinals=selected_ordinals,
        selected_keys=selected_keys,
    )
    return PipelineInputs(detector_source, detector_lookup, hooks), truth
